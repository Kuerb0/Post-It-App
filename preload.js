const {contextBridge,ipcRenderer:r}=require('electron');
contextBridge.exposeInMainWorld('api',{
  get:id=>r.invoke('get',id),
  save:(id,html,alarms)=>r.send('save',id,html,alarms),
  color:(id,c)=>r.send('color',id,c),
  z:id=>r.invoke('z',id),
  glass:id=>r.invoke('glass',id),
  cols:(id,v)=>r.send('cols',id,v),
  add:()=>r.send('new'),
  del:id=>r.send('del',id),
  close:()=>r.send('close'),
  min:()=>r.send('min'),
  cal:id=>r.invoke('cal',id),
  agenda:()=>r.invoke('agenda'),
  refrescar:()=>r.invoke('refrescar'),
  estilo:()=>r.invoke('estilo'),
  setEstilo:(f,l)=>r.send('estilo',f,l),
  onEstilo:f=>r.on('estilo',(_,e)=>f(e)),
  icsGet:()=>r.invoke('ics:get'),
  icsProbar:u=>r.invoke('ics:probar',u),
  icsGuardar:u=>r.invoke('ics:guardar',u),
  hechoCal:(id,k,v)=>r.send('hechoCal',id,k,v),
  lanz:(a,id)=>r.send('lanz',a,id),
  onLanz:f=>r.on('lanz',(_,l)=>f(l)),
  onSet:f=>r.on('set',(_,n)=>f(n)),
  onAgenda:f=>r.on('agenda',(_,ev)=>f(ev)),
});
